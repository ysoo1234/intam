import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SOURCE_PATH = path.resolve(
  "assets-source/world/village-walkable-mask-v9.png",
);
const OUTPUT_PATH = path.resolve(
  "src/game/features/world/model/villageCollisionMask.ts",
);
const PREVIEW_PATH = path.resolve("tmp/village-collision-preview.png");
const CELL_SIZE = 4;
const MAP_WIDTH = 1_280;
const MAP_HEIGHT = 720;

function isPathPixel(red, green, blue) {
  // v5: the plaza floor and its walls share the same cream, so the walkable
  // area is a hand-drawn mask (white = walkable) made by
  // assets-source/world/build_garden_walkable_mask_v8.py (v9 output).
  return red >= 128 && green >= 128 && blue >= 128;
}

function removeIsolatedCells(source, columns, rows) {
  const result = Uint8Array.from(source);

  for (let row = 1; row < rows - 1; row += 1) {
    for (let column = 1; column < columns - 1; column += 1) {
      const index = row * columns + column;
      let blockedNeighbors = 0;
      for (let offsetY = -1; offsetY <= 1; offsetY += 1) {
        for (let offsetX = -1; offsetX <= 1; offsetX += 1) {
          if (offsetX === 0 && offsetY === 0) continue;
          blockedNeighbors +=
            source[(row + offsetY) * columns + column + offsetX];
        }
      }

      if (source[index] === 1 && blockedNeighbors <= 1) result[index] = 0;
      if (source[index] === 0 && blockedNeighbors >= 7) result[index] = 1;
    }
  }

  return result;
}

function encodeBitset(cells) {
  const bytes = Buffer.alloc(Math.ceil(cells.length / 8));
  for (let index = 0; index < cells.length; index += 1) {
    if (cells[index] === 1) bytes[index >> 3] |= 1 << (index & 7);
  }
  return bytes.toString("base64");
}

function wrapString(value, width = 96) {
  const parts = [];
  for (let index = 0; index < value.length; index += width) {
    parts.push(`  "${value.slice(index, index + width)}"`);
  }
  return parts.join(" +\n");
}

const sourceBytes = await readFile(SOURCE_PATH);
const sourceSha256 = createHash("sha256").update(sourceBytes).digest("hex");
const { data, info } = await sharp(sourceBytes)
  .resize(MAP_WIDTH, MAP_HEIGHT, {
    fit: "fill",
    kernel: sharp.kernel.lanczos3,
  })
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
const columns = Math.ceil(info.width / CELL_SIZE);
const rows = Math.ceil(info.height / CELL_SIZE);
const sampledCells = new Uint8Array(columns * rows);

for (let row = 0; row < rows; row += 1) {
  for (let column = 0; column < columns; column += 1) {
    let pathPixels = 0;
    let sampledPixels = 0;
    for (let offsetY = 0; offsetY < CELL_SIZE; offsetY += 1) {
      for (let offsetX = 0; offsetX < CELL_SIZE; offsetX += 1) {
        const x = Math.min(
          info.width - 1,
          column * CELL_SIZE + offsetX,
        );
        const y = Math.min(
          info.height - 1,
          row * CELL_SIZE + offsetY,
        );
        const pixelIndex = (y * info.width + x) * info.channels;
        if (
          isPathPixel(
            data[pixelIndex],
            data[pixelIndex + 1],
            data[pixelIndex + 2],
          )
        ) {
          pathPixels += 1;
        }
        sampledPixels += 1;
      }
    }
    sampledCells[row * columns + column] =
      pathPixels / sampledPixels >= 0.55 ? 0 : 1;
  }
}

const collisionCells = removeIsolatedCells(sampledCells, columns, rows);
const bitsetBase64 = encodeBitset(collisionCells);
const output = `// Generated by scripts/generate-village-collision-mask.mjs.
// This checked-in mask is deliberately independent from the runtime WebP.
// Regenerate only when the approved walkable layout changes.

export const VILLAGE_COLLISION_MASK = {
  schemaVersion: 1,
  sourceSha256: "${sourceSha256}",
  mapWidth: ${info.width},
  mapHeight: ${info.height},
  cellSize: ${CELL_SIZE},
  columns: ${columns},
  rows: ${rows},
  encoding: "base64-bitset",
  bitsetBase64:
${wrapString(bitsetBase64)},
} as const;
`;

await writeFile(OUTPUT_PATH, output, "utf8");
console.log(
  `Wrote ${path.relative(process.cwd(), OUTPUT_PATH)} (${columns}x${rows} cells).`,
);

if (process.argv.includes("--preview")) {
  const overlay = Buffer.alloc(MAP_WIDTH * MAP_HEIGHT * 4);
  for (let y = 0; y < MAP_HEIGHT; y += 1) {
    for (let x = 0; x < MAP_WIDTH; x += 1) {
      const cell =
        Math.floor(y / CELL_SIZE) * columns + Math.floor(x / CELL_SIZE);
      if (collisionCells[cell] !== 1) continue;
      const index = (y * MAP_WIDTH + x) * 4;
      overlay[index] = 218;
      overlay[index + 1] = 58;
      overlay[index + 2] = 74;
      overlay[index + 3] = 118;
    }
  }
  await mkdir(path.dirname(PREVIEW_PATH), { recursive: true });
  await sharp(sourceBytes)
    .resize(MAP_WIDTH, MAP_HEIGHT, { fit: "fill" })
    .composite([
      {
        input: overlay,
        raw: { width: MAP_WIDTH, height: MAP_HEIGHT, channels: 4 },
      },
    ])
    .png()
    .toFile(PREVIEW_PATH);
  console.log(`Wrote ${path.relative(process.cwd(), PREVIEW_PATH)}`);
}
